#!/usr/bin/env python3
"""
Fetches the latest uploads from the YouTube channel and saves them to videos.js.

Runs automatically on GitHub (see .github/workflows/update-site.yml).
You can also run it yourself:  python3 scripts/update_videos.py

Videos already in videos.js are kept, so the list grows over time even though
YouTube's feed only ever shows the newest 15.
"""
import json
import pathlib
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

CHANNEL_ID = "UCh32x5A9ODWhGV-QkfFBsWw"  # NoobJerry

# Tag rules: if the video title matches the pattern, it gets that tag.
# A video that matches nothing gets DEFAULT_TAG.
TAG_RULES = [
    ("wuthering waves", r"wuthering"),
    ("sim racing", r"iracing|automobilista|\bams2\b|assetto|\bacc\b|forza|\bgt3\b|hotlap|"
                   r"le mans|\blmu\b|\blmdh\b|rfactor|nurburgring|n[uü]rburgring"),
]
DEFAULT_TAG = "gaming"

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "videos.js"
FEED = f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}"
# YouTube keeps a Shorts-only list for every channel: "UUSH" + the channel ID without "UC".
SHORTS_FEED = f"https://www.youtube.com/feeds/videos.xml?playlist_id=UUSH{CHANNEL_ID[2:]}"
NS = {"a": "http://www.w3.org/2005/Atom",
      "yt": "http://www.youtube.com/xml/schemas/2015",
      "media": "http://search.yahoo.com/mrss/"}
HEADER = ("// AUTO-GENERATED by scripts/update_videos.py - don't edit by hand.\n"
          "// To change a video's title/tags or feature it, add it to content.js instead\n"
          "// (entries there win). To hide one, add its ID to hideVideos in content.js.\n")


def tags_for(title):
    tags = [tag for tag, pattern in TAG_RULES if re.search(pattern, title, re.I)]
    return tags or [DEFAULT_TAG]


def short_description(text):
    for line in (text or "").splitlines():
        line = line.strip()
        if line and "http" not in line and not line.startswith("#") and not line.endswith(":"):
            return line[:160]
    return ""


def load_existing():
    if not OUT.exists():
        return []
    body = OUT.read_text(encoding="utf-8")
    start, end = body.find("["), body.rfind("]")
    return json.loads(body[start:end + 1]) if start != -1 else []


def fetch_feed(url, short=False):
    req = urllib.request.Request(url, headers={"User-Agent": "site-video-updater"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        root = ET.fromstring(resp.read())
    videos = []
    for e in root.findall("a:entry", NS):
        vid = e.findtext("yt:videoId", namespaces=NS)
        title = (e.findtext("a:title", namespaces=NS) or "").strip()
        published = (e.findtext("a:published", namespaces=NS) or "")[:10]
        desc = e.findtext("media:group/media:description", namespaces=NS)
        if vid:
            videos.append({"title": title, "date": published, "tags": tags_for(title),
                           "youtubeId": vid, "description": short_description(desc), "short": short})
    return videos


def main():
    try:
        shorts = fetch_feed(SHORTS_FEED, short=True)
        short_ids = {v["youtubeId"] for v in shorts}
        uploads = [v for v in fetch_feed(FEED) if v["youtubeId"] not in short_ids]
        fresh = uploads + shorts
    except Exception as err:  # network hiccup: keep the old file, don't fail the site build
        print(f"Could not read the YouTube feed: {err}", file=sys.stderr)
        return
    by_id = {v["youtubeId"]: v for v in load_existing()}
    added = [v for v in fresh if v["youtubeId"] not in by_id]
    for v in fresh:  # refresh titles/dates of known videos too
        by_id[v["youtubeId"]] = v
    videos = sorted(by_id.values(), key=lambda v: v["date"], reverse=True)
    OUT.write_text(HEADER + "window.AUTO_VIDEOS = " + json.dumps(videos, indent=2, ensure_ascii=False) + ";\n",
                   encoding="utf-8")
    print(f"{len(added)} new video(s), {len(videos)} total.")
    for v in added:
        print(f"  + {v['date']}  {'[Short] ' if v.get('short') else ''}{v['title']}")


if __name__ == "__main__":
    main()
