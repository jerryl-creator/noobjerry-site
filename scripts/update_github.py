#!/usr/bin/env python3
"""
Collects your public GitHub projects, releases and recent commits into github.js
for the site's GitHub tab.

Runs automatically on GitHub (see .github/workflows/update-site.yml).
You can also run it yourself:  python3 scripts/update_github.py
(Without a token GitHub allows 60 requests an hour, which is plenty for this.)
"""
import json
import os
import pathlib
import re
import sys
import urllib.request

USER = "jerryl-creator"
HIDE_REPOS = set()            # repo names to leave out, e.g. {"old-test"}
MAX_COMMITS_PER_REPO = 15
MAX_CHANGELOG = 40            # entries kept in the changelog
BOTS = ("github-actions[bot]", "dependabot[bot]")

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "github.js"
HEADER = ("// AUTO-GENERATED by scripts/update_github.py - don't edit by hand.\n"
          "// It's refreshed from your public GitHub account on every site update.\n")


def api(path):
    req = urllib.request.Request(f"https://api.github.com/{path}", headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "site-github-updater",
        **({"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}"} if os.environ.get("GITHUB_TOKEN") else {}),
    })
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def plain_summary(markdown, limit=200):
    """First real sentence/paragraph of release notes, without markdown."""
    for line in (markdown or "").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "|", "-", "*", ">", "```", "!")):
            continue
        line = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", line)          # images
        line = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", line)        # links -> text
        line = re.sub(r"[*_`]+", "", line).strip()                  # bold/italic/code
        if len(line) > 20:
            return line if len(line) <= limit else line[: limit - 1].rsplit(" ", 1)[0] + "…"
    return ""


def main():
    try:
        repos = [r for r in api(f"users/{USER}/repos?per_page=100&sort=pushed")
                 if not r["fork"] and not r["private"] and not r["archived"] and r["name"] not in HIDE_REPOS]
        projects, log = [], []
        for r in repos:
            name = r["name"]
            releases = [x for x in api(f"repos/{USER}/{name}/releases?per_page=10") if not x["draft"]]
            latest = next((x for x in releases if not x["prerelease"]), None)
            projects.append({
                "name": name,
                "url": r["html_url"],
                "description": r["description"] or "",
                "language": r["language"] or "",
                "stars": r["stargazers_count"],
                "topics": r.get("topics", [])[:4],
                "updated": r["pushed_at"][:10],
                "homepage": r["homepage"] or "",
                "release": {"tag": latest["tag_name"], "url": latest["html_url"], "date": latest["published_at"][:10]} if latest else None,
            })
            for x in releases:
                log.append({
                    "kind": "release", "repo": name, "date": x["published_at"][:19],
                    "title": x["name"] or x["tag_name"], "tag": x["tag_name"],
                    "text": plain_summary(x["body"]), "url": x["html_url"],
                })
            # "Nyanspect 2.0.2"-style version-bump commits just repeat their release.
            norm = lambda t: re.sub(r"\bv(?=\d)", "", t.lower()).strip()
            release_titles = {norm(x["name"] or x["tag_name"]) for x in releases}
            for c in api(f"repos/{USER}/{name}/commits?per_page={MAX_COMMITS_PER_REPO}"):
                who = (c.get("author") or {}).get("login") or c["commit"]["author"]["name"]
                first_line = c["commit"]["message"].splitlines()[0]
                if who in BOTS or norm(first_line) in release_titles:
                    continue
                log.append({
                    "kind": "commit", "repo": name, "date": c["commit"]["author"]["date"][:19],
                    "title": c["commit"]["message"].splitlines()[0][:140],
                    "sha": c["sha"][:7], "url": c["html_url"],
                })
    except Exception as err:  # network hiccup: keep the old file, don't fail the site build
        print(f"Could not read GitHub: {err}", file=sys.stderr)
        return

    log.sort(key=lambda e: e["date"], reverse=True)
    data = {"user": USER, "url": f"https://github.com/{USER}", "projects": projects, "changelog": log[:MAX_CHANGELOG]}
    OUT.write_text(HEADER + "window.GITHUB_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n",
                   encoding="utf-8")
    print(f"{len(projects)} project(s), {len(data['changelog'])} changelog entries.")


if __name__ == "__main__":
    main()
